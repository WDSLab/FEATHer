# -*- coding: utf-8 -*-
"""Export weights + golden vectors for FEATHer-CI (channel_mode="ci_full").

Same frozen architecture as export_golden_feather2.py; the only difference is
that channels are folded into the batch, so every layer is built at WIDTH 1 and
the weights are shared across channels.  That is why this writes the same
golden/feather2_weights.h the mixing variant uses - the C port is
feather2_infer.c compiled with -DFEA2_D=1, driven per channel by
src/feather2ci_infer.c.  There is no second forward implementation.

    ! The two exports overwrite the same weights header.  Regenerate before
      each build (measure_footprint.py already does).

Run:
    python deployment/board/export_golden_feather2ci.py --pred_len 720 --d_model 32
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import torch
import torch.nn.functional as F

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from baselines.FEATHer.FEATHer import FEATHer  # noqa: E402
from export_golden_feather2 import (ARCH, SEQ_LEN, PERIOD, WEIGHT_SEED,   # noqa: E402
                                    INPUT_SEED, OUT_DIR, emit_array)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pred_len", type=int, default=96)
    ap.add_argument("--d_model", type=int, default=7)
    ap.add_argument("--ckpt", type=str, default=None)
    ap.add_argument("--mlp_rank", type=int, default=ARCH["mlp_rank"],
                    help="residual MLP rank; the C header takes -DFEA2_MLP_R to match")
    ap.add_argument("--period", type=int, default=PERIOD,
                    help="SPK period (10-12); the C header takes -DFEA2_PERIOD to match")
    a = ap.parse_args()
    H, D, P = a.pred_len, a.d_model, a.period
    assert H % P == 0, "pred_len must be divisible by period"

    arch = dict(ARCH)
    arch["channel_mode"] = "ci_full"
    arch["mlp_rank"] = a.mlp_rank
    torch.manual_seed(WEIGHT_SEED)
    m = FEATHer(seq_len=SEQ_LEN, pred_len=H, d_model=D,
                use_norm=True, period=P, **arch).eval()
    if a.ckpt:
        sd = torch.load(a.ckpt, map_location="cpu")
        sd = sd.get("model_state_dict", sd.get("state_dict", sd))
        m.load_state_dict({k.replace("module.", ""): v for k, v in sd.items()},
                          strict=True)
        print(f"loaded checkpoint {a.ckpt}")
    else:
        torch.manual_seed(WEIGHT_SEED + 1)
        with torch.no_grad():
            m.freq_gate.proj.weight.normal_(0.0, 0.5)
            m.freq_gate.proj.bias.normal_(0.0, 0.5)

    n_params = sum(p.numel() for p in m.parameters())
    # ci_full builds every layer at width 1, so the parameter count must NOT
    # depend on D.  If it does, the variant was not actually folded.
    assert m.conv_point.weight.shape[0] == 1, "ci_full did not build at width 1"
    print(f"params = {n_params}  (L={SEQ_LEN} H={H} D={D} P={P}, width-1)")

    g = torch.Generator().manual_seed(INPUT_SEED)
    x = torch.randn(1, SEQ_LEN, D, generator=g)
    with torch.no_grad():
        y = m(x)

        # guard: the C port runs the width-1 network once per channel and
        # concatenates.  Verify that is exactly what ci_full computes.
        cols = []
        for c in range(D):
            cols.append(m(x[:, :, c:c + 1]))
        y_loop = torch.cat(cols, dim=2)
        dmax = (y_loop - y).abs().max().item()
        print(f"per-channel loop equivalence: max|diff| = {dmax:.3e}")
        assert dmax < 1e-5, "ci_full is not a per-channel application"

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with (OUT_DIR / "feather2_weights.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by export_golden_feather2ci.py"
                " - do not edit.  WIDTH-1 (ci_full) weights. */\n")
        src = a.ckpt if a.ckpt else f"random seed={WEIGHT_SEED}"
        f.write(f"/* source={src}, params={n_params}, H={H}, ci_full */\n")
        f.write("#ifndef FEATHER2_WEIGHTS_H\n#define FEATHER2_WEIGHTS_H\n\n")
        f.write(f"#define FEA2_H_GEN {H}\n")
        f.write(f"#define FEA2_R_GEN {arch['mlp_rank']}\n")
        f.write(f"#define FEA2_P_GEN {P}\n\n")
        emit_array(f, "W_CONVP", m.conv_point.weight)
        emit_array(f, "B_CONVP", m.conv_point.bias)
        emit_array(f, "W_CONVM", m.conv_mid.weight)
        emit_array(f, "B_CONVM", m.conv_mid.bias)
        emit_array(f, "W_GATE2", m.freq_gate.proj.weight)
        emit_array(f, "B_GATE2", m.freq_gate.proj.bias)
        emit_array(f, "W_NLDOWN2", m.nl_down.weight)
        emit_array(f, "B_NLDOWN2", m.nl_down.bias)
        emit_array(f, "W_NLUP2", m.nl_up.weight)
        emit_array(f, "B_NLUP2", m.nl_up.bias)
        emit_array(f, "W_AGG2", m.sparse_head.agg_conv.weight)
        emit_array(f, "W_BB2", m.sparse_head.backbone.weight)
        f.write("#endif /* FEATHER2_WEIGHTS_H */\n")

    with (OUT_DIR / "feather2ci_vectors.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by export_golden_feather2ci.py"
                " - do not edit. */\n")
        f.write(f"/* weight_seed={WEIGHT_SEED}, input_seed={INPUT_SEED}, "
                f"H={H}, D={D}, loop max|diff|={dmax:.3e} */\n")
        f.write("#ifndef FEATHER2CI_VECTORS_H\n#define FEATHER2CI_VECTORS_H\n\n")
        f.write(f"#define GCI_D {D}\n#define GCI_H {H}\n\n")
        emit_array(f, "GCI_X", x[0])       # (L, D) time-major
        emit_array(f, "GCI_Y", y[0])       # (H, D) time-major
        f.write("#endif /* FEATHER2CI_VECTORS_H */\n")

    print(f"wrote {OUT_DIR / 'feather2_weights.h'} (width-1)")
    print(f"wrote {OUT_DIR / 'feather2ci_vectors.h'}")


if __name__ == "__main__":
    main()
