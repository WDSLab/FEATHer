# -*- coding: utf-8 -*-
"""Const plans for src/mcu_pocket.c = what pocketfft's make_*_plan computes (factor order, twiddle tables).
Real: pocketfft C rfftp_factorize / rfftp_comp_twiddle (same as the C++ rfftp).  Complex: the C++ cfftp (8 first).
A plan is made per direction and names each factor's pass function (mcu_pocket.h).
write_rfft96() = the 96-point real plans MCU_RFFT96_F / _B (golden/mcu_rfft96_plan.h)."""
from pathlib import Path

import numpy as np

NFCT = 8


def _odd(n, f):
    d = 3
    while d * d <= n:
        while n % d == 0:
            f.append(d)
            n //= d
        d += 2
    if n > 1:
        f.append(n)
    return f


def rfactors(n):
    f = []
    while n % 4 == 0:
        f.append(4)
        n //= 4
    if n % 2 == 0:
        n //= 2
        f.append(2)
        f[0], f[-1] = f[-1], f[0]
    return _odd(n, f)


def cfactors(n):
    f = []
    while n % 8 == 0:
        f.append(8)
        n //= 8
    while n % 4 == 0:
        f.append(4)
        n //= 4
    if n % 2 == 0:
        n //= 2
        f.append(2)
        f[0], f[-1] = f[-1], f[0]
    return _odd(n, f)


def _fl(v):
    return f"{float(np.float32(v))!r}f"


def _arr(name, vals):
    vals = list(vals) or [0.0]
    body = ",\n".join("    " + ", ".join(_fl(v) for v in vals[i:i + 6]) for i in range(0, len(vals), 6))
    return f"static const float {name}[{len(vals)}] = {{\n{body}\n}};"


def rplan(name, n, dirs="f"):
    """Real plan(s) of length n: {name}_F (forward) and / or {name}_B (backward), one twiddle table."""
    fac = rfactors(n)
    assert len(fac) <= NFCT, (n, fac)
    w = lambda k: np.exp(2j * np.pi * k / n)
    mem, ent, l1 = [], [], 1
    for k, ip in enumerate(fac):
        ido = n // (l1 * ip)
        tw = tws = "0"
        if k < len(fac) - 1:
            tw = f"{name}_mem + {len(mem)}"
            t = np.zeros((ip - 1) * (ido - 1))
            for j in range(1, ip):
                for i in range(1, (ido - 1) // 2 + 1):
                    z = w(j * l1 * i)
                    t[(j - 1) * (ido - 1) + 2 * i - 2], t[(j - 1) * (ido - 1) + 2 * i - 1] = z.real, z.imag
            mem += list(t)
        if ip > 5:
            tws = f"{name}_mem + {len(mem)}"
            t = np.zeros(2 * ip)
            t[0] = 1.0
            for i in range(1, (ip >> 1) + 1):
                z = w(i * (n // ip))
                t[2 * i], t[2 * i + 1] = z.real, z.imag
                t[2 * (ip - i)], t[2 * (ip - i) + 1] = z.real, -z.imag
            mem += list(t)
        ent.append((ip, tw, tws))
        l1 *= ip
    out = [_arr(f"{name}_mem", mem)]
    for d in dirs:
        fn = lambda ip: f"pk_rad{d}{ip}, 0" if ip <= 5 else f"0, pk_rad{d}g"
        out.append(f"static const rfftp_plan_i {name}_{d.upper()} = {{{n}, {len(fac)}, {{"
                   + ", ".join(f"{{{ip}, {tw}, {tws}, {fn(ip)}}}" for ip, tw, tws in ent) + "}};")
    return "\n".join(out)


def cplan(name, n, backward):
    """Complex plan of length n for one direction."""
    fac = cfactors(n)
    assert len(fac) <= NFCT and set(fac) <= {2, 3, 4, 5, 7, 8, 11}, (n, fac)
    d = "b" if backward else "f"
    mem, ent, l1 = [], [], 1
    for ip in fac:
        ido = n // (l1 * ip)
        fn = f"0, pk_pass{ip}" if ip in (7, 11) else f"pk_pass{ip}{d}, 0"
        ent.append(f"{{{ip}, (const cmplx *)({name}_mem + {len(mem)}), 0, {fn}}}")
        for j in range(1, ip):
            for i in range(1, ido):
                z = np.exp(2j * np.pi * (j * l1 * i) / n)
                mem += [z.real, z.imag]
        l1 *= ip
    return (_arr(f"{name}_mem", mem) + f"\nstatic const cfftp_plan_i {name} = "
            f"{{{n}, {len(fac)}, {1 if backward else -1}, {{{', '.join(ent)}}}}};")


def write(path: Path, plans) -> Path:
    """One header of plans (texts from rplan / cplan); the guard is the file name."""
    path.parent.mkdir(parents=True, exist_ok=True)
    guard = path.name.upper().replace(".", "_")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("/* Auto-generated by deployment/board/export/pocket_plan.py - do not edit. */\n"
                f"#ifndef {guard}\n#define {guard}\n#include \"mcu_pocket.h\"\n" + "\n".join(plans) + "\n#endif\n")
    return path


def write_rfft96(out_dir: Path) -> Path:
    return write(out_dir / "mcu_rfft96_plan.h", [rplan("MCU_RFFT96", 96, "fb")])
