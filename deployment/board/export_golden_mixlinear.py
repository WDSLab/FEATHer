# -*- coding: utf-8 -*-
"""Export golden vectors + weights for the MixLinear companion port.

MixLinear (ICLR 2026, 49 params, D-independent) — FEATHer's closest sub-1K
rival. Config = SparseTSF-symmetric period_len=24 (seq=96, pred=96):
    seg_num_x = seg_num_y = 4, sqrt = 2, lpf = 4.
So all matmuls are tiny: conv1d(1->1, k=25), TLinear{1,2}=Linear(2,2),
FLinear1=cLinear(4->2), FLinear2=cLinear(2->4); freq FFT length = 4.

Stages the upstream forward and asserts equality with model(x) before writing
weights (conv/TLinear real + FLinear complex re/im), golden vectors, and the
4-point DFT twiddle table.

Run:  python deployment/board/export_golden_mixlinear.py
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import torch
import torch.nn.functional as F

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from tools.results.protocol import resolve  # noqa: E402
from baselines.MixLinear.wrapper import build   # noqa: E402
from export_golden import emit_array             # noqa: E402

SEQ_LEN = 96
PRED_LEN = 96
D_MODEL = 7
PERIOD_LEN = 24

WEIGHT_SEED = 2025
INPUT_SEED = 7
OUT_DIR = Path(__file__).resolve().parent / "golden"


def main() -> None:
    global PRED_LEN
    global D_MODEL
    _cli = argparse.ArgumentParser()
    _cli.add_argument("--pred_len", type=int, default=PRED_LEN,
                      help="board horizon; the C header takes -D<PFX>_H to match")
    _cli.add_argument("--d_model", type=int, default=D_MODEL,
                      help="channel count; the C header takes -D<PFX>_D to match")
    # 2026-10-07: one of the industrial candidate settings (resolved as the experiments
    # do); lpf and alpha then go to mixlinear_geom.h.  Omitted = the old default.
    _cli.add_argument("--data", default="MetroPT3")
    _cli.add_argument("--config", default=None,
                      help="industrial candidate (ETTh1 / ETTh2 / Electricity / Traffic)")
    _a = _cli.parse_args()
    PRED_LEN, D_MODEL = _a.pred_len, _a.d_model
    ns = argparse.Namespace()
    if _a.config:
        _, _, ov = resolve("MixLinear", "mfg", _a.data, PRED_LEN, "cand:" + _a.config)
        ns = argparse.Namespace(**ov)
        assert int(ov.get("mixlinear_period_len", 24)) == PERIOD_LEN, "the port is written for period 24"
    torch.manual_seed(WEIGHT_SEED)
    wrapped = build(ns, D_MODEL, SEQ_LEN, PRED_LEN).eval()
    m = wrapped.model  # raw upstream Model (weights live here)

    # Golden weights must exercise every arithmetic path of the port.  The
    # upstream init leaves the IMAGINARY part of both complex linears at 0,
    # so every imaginary-weight term multiplied zero and an error there would
    # still pass (found 2026-09-14).  Fill it with the same spread as the real
    # part; the staged == model(x) assert below still guards the reference.
    gw = torch.Generator().manual_seed(WEIGHT_SEED + 1)
    with torch.no_grad():
        for p in (m.FLinear1.weight, m.FLinear2.weight):
            im = torch.randn(p.shape, generator=gw) * p.real.std()
            p.copy_(torch.complex(p.real.clone(), im))

    n_params = sum(p.numel() for p in m.parameters())
    print(f"params = {n_params} (expect 49)")

    # geometry
    seg_x = math.ceil(SEQ_LEN / PERIOD_LEN)          # 4
    seg_y = math.ceil(PRED_LEN / PERIOD_LEN)         # 4
    sq_x = math.ceil(math.sqrt(SEQ_LEN / PERIOD_LEN))   # 2
    sq_y = math.ceil(math.sqrt(PRED_LEN / PERIOD_LEN))  # 2
    lpf = m.lpf
    # geometry guard: these constants describe the FROZEN H=96 cell
    # (the reference the 08-24 board numbers were taken at).  At other
    # horizons the geometry legitimately changes - print it instead, and
    # the C header must be given matching -D overrides.
    if PRED_LEN == 96 and not _a.config:
        assert (seg_x, seg_y, sq_x, sq_y, lpf) == (4, 4, 2, 2, 4), \
            f"unexpected geometry {(seg_x, seg_y, sq_x, sq_y, lpf)}"

    # Emit the geometry the C port must be built with.  Passing it by hand
    # (-DML_SQY=...) is a silent-wrong-answer waiting to happen: the code
    # would compile and produce a plausible forecast with the wrong
    # factorisation.  Generating it next to the weights makes that impossible.
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    _geom = [
        "/* Auto-generated by export_golden_mixlinear.py - do not edit. */",
        "#ifndef MIXLINEAR_GEOM_H", "#define MIXLINEAR_GEOM_H",
        f"#define ML_H {PRED_LEN}",
        f"#define ML_SEGY_G {seg_y}",
        f"#define ML_SQX {sq_x}   /* ceil(sqrt(L/P)) */",
        f"#define ML_SQY {sq_y}   /* ceil(sqrt(H/P)) */",
        f"#define ML_LPF {lpf}   /* kept FFT bins (<= seg_x) */",
        f"#define ML_ALPHA {m.alpha:.9e}f   /* time / frequency mix */",
        f"/* config={_a.config or 'default'} */",
        "#endif", "",
    ]
    (OUT_DIR / "mixlinear_geom.h").write_text(chr(10).join(_geom), encoding="utf-8")
    print(f"geometry: seg_x={seg_x} seg_y={seg_y} sq_x={sq_x} sq_y={sq_y} lpf={lpf}")

    g = torch.Generator().manual_seed(INPUT_SEED)
    x0 = torch.randn(1, SEQ_LEN, D_MODEL, generator=g)

    with torch.no_grad():
        # ---- staged replication of MixLinear.forward ----
        seq_mean = torch.mean(x0, dim=1).unsqueeze(1)          # (1,1,D)
        x = (x0 - seq_mean).permute(0, 2, 1)                   # (1,D,S)
        xc = m.conv1d(x.reshape(-1, 1, SEQ_LEN)).reshape(-1, D_MODEL, SEQ_LEN) + x
        xr = xc.reshape(1, D_MODEL, -1, PERIOD_LEN).permute(0, 1, 3, 2)  # (1,D,P,seg_x)

        # time branch
        x_o = F.pad(xr, (0, sq_x ** 2 - xr.shape[-1], 0, 0, 0, 0))
        x_o = x_o.reshape(1, D_MODEL, PERIOD_LEN, sq_x, sq_x)
        x_o = m.TLinear1(x_o).permute(0, 1, 2, 4, 3)
        x_t = m.TLinear2(x_o).permute(0, 1, 2, 4, 3)
        x_t = x_t.reshape(1, D_MODEL, PERIOD_LEN, -1).permute(0, 1, 3, 2) \
                 .reshape(1, D_MODEL, -1).permute(0, 2, 1)     # (1,?,D)

        # freq branch
        x_fft = torch.fft.fft(xr, dim=3)[:, :, :, :lpf]        # (1,D,P,lpf) cfloat
        x_fft = m.FLinear1(x_fft)                              # (1,D,P,2)
        x_fft = m.FLinear2(x_fft).reshape(1, D_MODEL, PERIOD_LEN, -1)  # (1,D,P,seg_y)
        x_rfft = torch.fft.ifft(x_fft, dim=3).float()          # (1,D,P,seg_y)
        x_f = x_rfft.permute(0, 1, 3, 2).reshape(1, D_MODEL, -1).permute(0, 2, 1)

        out = x_t[:, :PRED_LEN, :] * m.alpha + seq_mean + x_f[:, :PRED_LEN, :] * (1 - m.alpha)
        y = out[:, :PRED_LEN, :]

        y_ref = wrapped(x0)
        max_err = (y - y_ref).abs().max().item()
        print(f"staged vs model max|diff| = {max_err:.3e}")
        assert max_err < 1e-5, "staged forward drifted from model.forward"

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # weights
    with (OUT_DIR / "mixlinear_weights.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by export_golden_mixlinear.py - do not edit. */\n")
        f.write(f"/* seed={WEIGHT_SEED}, params={n_params}, period_len={PERIOD_LEN}, "
                f"imag randomized seed={WEIGHT_SEED + 1} */\n")
        f.write("#ifndef MIXLINEAR_WEIGHTS_H\n#define MIXLINEAR_WEIGHTS_H\n\n")
        emit_array(f, "ML_CONV", m.conv1d.weight)                 # (1,1,25)
        emit_array(f, "ML_TL1", m.TLinear1.weight)                # (2,2)
        emit_array(f, "ML_TL2", m.TLinear2.weight)                # (2,2)
        emit_array(f, "ML_FL1_RE", m.FLinear1.weight.real)        # (2,4)
        emit_array(f, "ML_FL1_IM", m.FLinear1.weight.imag)
        emit_array(f, "ML_FL2_RE", m.FLinear2.weight.real)        # (4,2)
        emit_array(f, "ML_FL2_IM", m.FLinear2.weight.imag)
        f.write("#endif /* MIXLINEAR_WEIGHTS_H */\n")

    # golden vectors
    with (OUT_DIR / "mixlinear_vectors.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by export_golden_mixlinear.py - do not edit. */\n")
        f.write(f"/* weight_seed={WEIGHT_SEED}, input_seed={INPUT_SEED} */\n")
        f.write("#ifndef MIXLINEAR_VECTORS_H\n#define MIXLINEAR_VECTORS_H\n\n")
        # Stamp the geometry these vectors were produced at.  The test
        # _Static_asserts against it: building the port at a different
        # width compiles fine and compares against the wrong reference,
        # which is how a stale golden set looks like a code regression.
        # (ML_H is already safe - it comes from the generated geom header
        # - but stamp it too so the check reads like the other ports.)
        f.write(f"#define ML_D_GEN {D_MODEL}\n#define ML_H_GEN {PRED_LEN}\n\n")
        emit_array(f, "MG_X", x0[0])                 # (96,7) time-major
        emit_array(f, "MG_MEAN", seq_mean[0, 0])     # (7,)
        emit_array(f, "MG_XT", x_t[0])               # (96,7) time branch
        emit_array(f, "MG_XF", x_f[0])               # (96,7) freq branch
        emit_array(f, "MG_Y", y[0])                  # (96,7)
        f.write("#endif /* MIXLINEAR_VECTORS_H */\n")

    # 4-point DFT twiddle (cos/sin of 2*pi*i/4)
    with (OUT_DIR / "mixlinear_twiddle.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by export_golden_mixlinear.py - do not edit. */\n")
        f.write("#ifndef MIXLINEAR_TWIDDLE_H\n#define MIXLINEAR_TWIDDLE_H\n\n")
        # FORWARD transform runs over seg_x points, INVERSE over seg_y.  Those
        # are both 4 at H=96, which hid a bug: the port used the seg_x table for
        # both and produced a wrong forecast at every other horizon (caught
        # 2026-09-04 by the H=192 golden run).  Emit both tables.
        for name, fn, n in (("ML_COS4", math.cos, seg_x),
                            ("ML_SIN4", math.sin, seg_x),
                            ("ML_COSY", math.cos, seg_y),
                            ("ML_SINY", math.sin, seg_y)):
            vals = ", ".join(f"{fn(2.0 * math.pi * j / n):.9e}f" for j in range(n))
            f.write(f"static const float {name}[{n}] = {{ {vals} }};\n")
        f.write("\n#endif /* MIXLINEAR_TWIDDLE_H */\n")

    print(f"wrote weights/vectors/twiddle -> {OUT_DIR}")
    print(f"alpha={m.alpha}  lpf={lpf}  seg_x={seg_x} seg_y={seg_y} sqrt={sq_x}")


if __name__ == "__main__":
    main()
