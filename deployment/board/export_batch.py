# -*- coding: utf-8 -*-
"""Export the 100-window batch golden set (week-2 acceptance criterion).

EDGE_EXPERIMENT.md decision #4, second half: the C port must reproduce the
PyTorch test MSE over 100 windows to 4 decimal places. This script draws
100 random (input, target) windows, runs every ported model in PyTorch
(same weight seed 2025 as the per-model golden exports -> identical
weights), and writes

    golden/batch_x.bin / batch_t.bin   float32 raw, C-order (100,96,7)
    golden/batch_ref.h                 float64 reference MSE per model

Run:  python deployment/board/export_batch.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import torch

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from baselines.FEATHer.FEATHer import FEATHer          # noqa: E402
from baselines.SparseTSF.wrapper import build as build_stsf   # noqa: E402
from baselines.DiPE_Linear.wrapper import build as build_dipe  # noqa: E402
from baselines.FITS.wrapper import build as build_fits  # noqa: E402

N = 100
SEQ_LEN = 96
PRED_LEN = 96
D_MODEL = 7
WEIGHT_SEED = 2025          # must match the per-model export scripts
BATCH_SEED = 123

OUT_DIR = Path(__file__).resolve().parent / "golden"


def mse64(pred: torch.Tensor, target: torch.Tensor) -> float:
    return ((pred.double() - target.double()) ** 2).mean().item()


def main() -> None:
    g = torch.Generator().manual_seed(BATCH_SEED)
    X = torch.randn(N, SEQ_LEN, D_MODEL, generator=g)
    T = torch.randn(N, PRED_LEN, D_MODEL, generator=g)

    refs = {}
    with torch.no_grad():
        torch.manual_seed(WEIGHT_SEED)
        m = FEATHer(seq_len=SEQ_LEN, pred_len=PRED_LEN, d_model=D_MODEL,
                    d_state=8, kernel_size=7, use_norm=True,
                    period=12, num_bands=3).eval()
        refs["FEATHER"] = mse64(m(X), T)

        torch.manual_seed(WEIGHT_SEED)
        m = build_stsf(argparse.Namespace(sparsetsf_period_len=24,
                                          sparsetsf_model_type="linear",
                                          sparsetsf_d_model=128),
                       D_MODEL, SEQ_LEN, PRED_LEN).eval()
        refs["STSF"] = mse64(m(X), T)

        torch.manual_seed(WEIGHT_SEED)
        m = build_dipe(argparse.Namespace(), D_MODEL, SEQ_LEN, PRED_LEN).eval()
        refs["DIPE"] = mse64(m(X), T)

        torch.manual_seed(WEIGHT_SEED)
        m = build_fits(argparse.Namespace(), D_MODEL, SEQ_LEN, PRED_LEN).eval()
        refs["FITS"] = mse64(m(X), T)

        pers = X[:, -1:, :].repeat(1, PRED_LEN, 1)
        refs["PERS"] = mse64(pers, T)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "batch_x.bin").write_bytes(
        X.to(torch.float32).contiguous().numpy().tobytes())
    (OUT_DIR / "batch_t.bin").write_bytes(
        T.to(torch.float32).contiguous().numpy().tobytes())

    with (OUT_DIR / "batch_ref.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by deployment/board/export_batch.py"
                " - do not edit. */\n")
        f.write(f"/* weight_seed={WEIGHT_SEED}, batch_seed={BATCH_SEED} */\n")
        f.write("#ifndef BATCH_REF_H\n#define BATCH_REF_H\n\n")
        f.write(f"#define BATCH_N {N}\n\n")
        for k, v in refs.items():
            f.write(f"static const double BATCH_REF_{k} = {v:.10f};\n")
        f.write("\n#endif /* BATCH_REF_H */\n")

    for k, v in refs.items():
        print(f"{k:8s} MSE = {v:.6f}")
    print(f"wrote {OUT_DIR}/batch_x.bin, batch_t.bin, batch_ref.h")


if __name__ == "__main__":
    main()
