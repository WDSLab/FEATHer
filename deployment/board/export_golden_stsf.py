# -*- coding: utf-8 -*-
"""Export golden vectors + weights for the SparseTSF companion port.

Config = the MetroPT3 deployment cell
(configs/SparseTSF.yaml: sparsetsf_period_len=24, model_type=linear) ->
n=m=4, conv k=25 => exactly 41 parameters (the paper headline count).

Uses the real upstream model via the benchmark wrapper (no re-implementation
drift); the staged replication is asserted equal to model(x) before writing.

Run:  python deployment/board/export_golden_stsf.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import torch

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from baselines.SparseTSF.wrapper import build  # noqa: E402
from golden_io import emit_array           # noqa: E402

SEQ_LEN = 96
PRED_LEN = 96
D_MODEL = 7
PERIOD = 24            # configs/SparseTSF.yaml (SparseTSF, MetroPT3)

WEIGHT_SEED = 2025
INPUT_SEED = 7

OUT_DIR = Path(__file__).resolve().parent / "golden"


def main() -> None:
    global PRED_LEN
    global D_MODEL
    global PERIOD
    _cli = argparse.ArgumentParser()
    _cli.add_argument("--pred_len", type=int, default=PRED_LEN,
                      help="board horizon; the C header takes -D<PFX>_H to match")
    _cli.add_argument("--d_model", type=int, default=D_MODEL,
                      help="channel count; the C header takes -D<PFX>_D to match")
    # the industrial period rule gives 48 on WindSCADA / BlastFurnace; the C
    # header takes -DSTSF_P to match (stamped below as STSF_P_GEN)
    _cli.add_argument("--period", type=int, default=PERIOD)
    _a = _cli.parse_args()
    PRED_LEN, D_MODEL, PERIOD = _a.pred_len, _a.d_model, _a.period
    torch.manual_seed(WEIGHT_SEED)
    args = argparse.Namespace(
        sparsetsf_period_len=PERIOD,
        sparsetsf_model_type="linear",
        sparsetsf_d_model=128,
    )
    model = build(args, D_MODEL, SEQ_LEN, PRED_LEN).eval()

    n_params = sum(p.numel() for p in model.parameters())
    print(f"params = {n_params}")
    # geometry guard for the reference H=96, P=24 cell; elsewhere the
    # geometry legitimately changes (the C header takes matching -D overrides).
    if PRED_LEN == 96 and PERIOD == 24:
        assert n_params == 41, f"expected the 41-param linear variant, got {n_params}"

    g = torch.Generator().manual_seed(INPUT_SEED)
    x = torch.randn(1, SEQ_LEN, D_MODEL, generator=g)

    n = SEQ_LEN // PERIOD
    with torch.no_grad():
        seq_mean = torch.mean(x, dim=1).unsqueeze(1)          # (1,1,D)
        xc = (x - seq_mean).permute(0, 2, 1)                  # (1,D,L)
        xa = model.conv1d(xc.reshape(-1, 1, SEQ_LEN)).reshape(
            -1, D_MODEL, SEQ_LEN) + xc                        # (1,D,L)
        xb = xa.reshape(-1, n, PERIOD).permute(0, 2, 1)       # (D,w,n)
        yb = model.linear(xb)                                 # (D,w,m)
        y = yb.permute(0, 2, 1).reshape(1, D_MODEL, PRED_LEN)
        y = y.permute(0, 2, 1) + seq_mean                     # (1,H,D)

        y_ref = model(x)
        assert torch.equal(y, y_ref), "staged forward drifted from model.forward"

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    with (OUT_DIR / "stsf_weights.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by deployment/board/export_golden_stsf.py"
                " - do not edit. */\n")
        f.write(f"/* seed={WEIGHT_SEED}, params={n_params} */\n")
        f.write("#ifndef STSF_WEIGHTS_H\n#define STSF_WEIGHTS_H\n\n")
        # Stamp the horizon the weights were generated at.  The port
        # static-asserts against it, so a stale golden header (weights
        # from one H, code built for another) fails to COMPILE instead of
        # silently producing a plausible wrong forecast.
        f.write(f"#define STSF_H_GEN {PRED_LEN}\n#define STSF_P_GEN {PERIOD}\n\n")
        emit_array(f, "STSF_W_CONV", model.conv1d.weight)   # (1,1,25)
        emit_array(f, "STSF_W_LIN", model.linear.weight)    # (4,4) out,in
        f.write("#endif /* STSF_WEIGHTS_H */\n")

    with (OUT_DIR / "stsf_vectors.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by deployment/board/export_golden_stsf.py"
                " - do not edit. */\n")
        f.write(f"/* weight_seed={WEIGHT_SEED}, input_seed={INPUT_SEED} */\n")
        f.write("#ifndef STSF_VECTORS_H\n#define STSF_VECTORS_H\n\n")
        # Width the golden vectors were captured at; the test
        # _Static_asserts against it (a port built at another width
        # compiles fine and fails numerically, which reads as a code bug).
        f.write(f"#define STSF_D_GEN {D_MODEL}\n\n")
        emit_array(f, "SG_X", x[0])            # (96,7) time-major
        emit_array(f, "SG_MEAN", seq_mean[0, 0])   # (7,)
        emit_array(f, "SG_XAGG", xa[0])        # (7,96) channel-major
        emit_array(f, "SG_Y", y[0])            # (96,7)
        f.write("#endif /* STSF_VECTORS_H */\n")

    print(f"wrote {OUT_DIR / 'stsf_weights.h'}")
    print(f"wrote {OUT_DIR / 'stsf_vectors.h'}")


if __name__ == "__main__":
    main()
