# -*- coding: utf-8 -*-
"""Export golden vectors + weights for FEATHer-mix WITHOUT bands + FFT gate.

The control arm FEATHer_frontnone (variants.FEATHerNoFront: hidden = x_norm, no
band bank, no gate).  This export feeds the FEA2_FRONT_NONE build of the shipping
recompute port (src/feather2r_infer.c), so the flash / SRAM / board latency of the
band + gate front end can be measured on the same chip.

Writes golden/feather2fn_weights.h and golden/feather2fn_vectors.h (own files:
the frozen model's feather2_*.h, which `make test` uses, stay untouched).  Every
weight is random (README: blind-golden rule) and the forecast is model(x).

Run:  python deployment/board/export_golden_feather2fn.py [--pred_len H] [--d_model D] [--mlp_rank 4]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import torch

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from baselines.FEATHer.variants import FEATHerNoFront  # noqa: E402
from export_golden_feather2 import ARCH, PERIOD, SEQ_LEN, emit_array   # noqa: E402

WEIGHT_SEED = 2025
INPUT_SEED = 7
OUT_DIR = Path(__file__).resolve().parent / "golden"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pred_len", type=int, default=96)
    ap.add_argument("--d_model", type=int, default=7)
    ap.add_argument("--mlp_rank", type=int, default=4)
    a = ap.parse_args()
    H, D = a.pred_len, a.d_model
    arch = dict(ARCH, mlp_rank=a.mlp_rank)

    torch.manual_seed(WEIGHT_SEED)
    m = FEATHerNoFront(seq_len=SEQ_LEN, pred_len=H, d_model=D, use_norm=True, period=PERIOD,
                       **arch).eval()
    with torch.no_grad():                       # blind-golden rule: all weights random
        for name, p in m.named_parameters():
            p.normal_(0.0, p.shape[-1] ** -0.5 if p.dim() >= 2 else 0.3)
    assert m.conv_point is None and m.freq_gate is None
    n_params = sum(p.numel() for p in m.parameters())
    print(f"front=none  params = {n_params}  (L={SEQ_LEN} H={H} D={D} R={a.mlp_rank})")

    g = torch.Generator().manual_seed(INPUT_SEED)
    x = torch.randn(1, SEQ_LEN, D, generator=g)
    with torch.no_grad():
        y = m(x)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with (OUT_DIR / "feather2fn_weights.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by deployment/board/export_golden_feather2fn.py - do not edit. */\n")
        f.write(f"/* front=none, random seed={WEIGHT_SEED}, params={n_params}, H={H} */\n")
        f.write("#ifndef FEATHER2FN_WEIGHTS_H\n#define FEATHER2FN_WEIGHTS_H\n\n")
        f.write(f"#define FEA2_H_GEN {H}\n#define FEA2_R_GEN {a.mlp_rank}\n#define FEA2_FN_GEN 1\n\n")
        emit_array(f, "W_NLDOWN2", m.nl_down.weight)            # (R,D) out,in
        emit_array(f, "B_NLDOWN2", m.nl_down.bias)              # (R,)
        emit_array(f, "W_NLUP2", m.nl_up.weight)                # (D,R) out,in
        emit_array(f, "B_NLUP2", m.nl_up.bias)                  # (D,)
        emit_array(f, "W_AGG2", m.sparse_head.agg_conv.weight)  # (D,1,25)
        emit_array(f, "W_BB2", m.sparse_head.backbone.weight)   # (m,n) out,in
        f.write("#endif /* FEATHER2FN_WEIGHTS_H */\n")

    with (OUT_DIR / "feather2fn_vectors.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by deployment/board/export_golden_feather2fn.py - do not edit. */\n")
        f.write(f"/* weight_seed={WEIGHT_SEED}, input_seed={INPUT_SEED}, H={H} */\n")
        f.write("#ifndef FEATHER2FN_VECTORS_H\n#define FEATHER2FN_VECTORS_H\n\n")
        f.write(f"#define FEA2_D_GEN {D}\n\n")
        emit_array(f, "G2_X", x[0])          # (L,D) time-major
        emit_array(f, "G2_Y", y[0])          # (H,D)
        f.write("#endif /* FEATHER2FN_VECTORS_H */\n")
    print(f"wrote {OUT_DIR / 'feather2fn_weights.h'}")
    print(f"wrote {OUT_DIR / 'feather2fn_vectors.h'}")


if __name__ == "__main__":
    main()
