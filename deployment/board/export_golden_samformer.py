# -*- coding: utf-8 -*-
"""Export golden vectors + weights for the SAMformer port (src/samformer_infer.c).

SAMformer (ICML 2024), the channel-mixing reference.  Every candidate setting
has the same structure (hid_dim 16; they differ in lr and SAM rho only), so
--config / --data are accepted for a uniform interface with the other config
exports and only checked to resolve.

Real upstream model via the benchmark wrapper; every weight re-drawn at
random (README: blind-golden rule; Linear weights scaled by 1/sqrt(fan_in),
RevIN gains around 1).  Stage vectors come from forward hooks on the model.

Run:  python deployment/board/export_golden_samformer.py [--pred_len H] [--d_model D]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import torch

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from baselines.SAMformer.wrapper import build     # noqa: E402
from tools.results.protocol import resolve        # noqa: E402
from golden_io import emit_array              # noqa: E402

WEIGHT_SEED = 2025
INPUT_SEED = 7

OUT_DIR = Path(__file__).resolve().parent / "golden"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pred_len", type=int, default=96)
    ap.add_argument("--seq_len", type=int, default=96)
    ap.add_argument("--d_model", type=int, default=7)
    ap.add_argument("--data", default="MetroPT3")
    ap.add_argument("--config", default="default")
    a = ap.parse_args()
    L, H, D = a.seq_len, a.pred_len, a.d_model
    _, _, ov = resolve("SAMformer", "mfg", a.data, H, "cand:" + a.config)
    hid = int(ov.get("samformer_hid_dim", 16))
    print(f"config={a.config} L={L} H={H} D={D} hid={hid}")

    torch.manual_seed(WEIGHT_SEED)
    model = build(argparse.Namespace(samformer_hid_dim=hid), D, L, H).eval()
    net = model.net
    with torch.no_grad():                       # blind-golden rule: all weights random
        for name, p in net.named_parameters():
            if name == "revin.affine_weight":
                p.copy_(1.0 + 0.3 * torch.randn_like(p))
            elif p.dim() == 2:
                p.normal_(0.0, p.shape[1] ** -0.5)
            else:
                p.normal_(0.0, 0.5)
    print(f"params = {sum(p.numel() for p in model.parameters())}")

    cap = {}
    net.linear_forecaster.register_forward_pre_hook(lambda m, i: cap.__setitem__("out", i[0].detach().clone()))
    g = torch.Generator().manual_seed(INPUT_SEED)
    x = (torch.randn(1, L, D, generator=g) * 3.0
         + torch.linspace(-5.0, 5.0, D).view(1, 1, D))
    with torch.no_grad():
        y_ref = model(x)
        mean = x.mean(dim=1)[0]
        std = torch.sqrt(x.var(dim=1, unbiased=False) + 1e-5)[0]
        xn = ((x - mean) / std * net.revin.affine_weight + net.revin.affine_bias).transpose(1, 2)   # (1,D,L)
        q, k = net.compute_queries(xn), net.compute_keys(xn)
        attw = torch.softmax(q @ k.transpose(-2, -1) / hid ** 0.5, dim=-1)[0]                     # (D,D)
    assert y_ref.shape == (1, H, D)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with (OUT_DIR / "samformer_weights.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by deployment/board/export_golden_samformer.py - do not edit. */\n")
        f.write(f"/* config={a.config}, seed={WEIGHT_SEED} */\n")
        f.write("#ifndef SAMFORMER_WEIGHTS_H\n#define SAMFORMER_WEIGHTS_H\n\n")
        f.write(f"#define SAM_H_GEN {H}\n#define SAM_L_GEN {L}\n#define SAM_D_GEN {D}\n#define SAM_HID {hid}\n\n")
        emit_array(f, "SAM_RV_W", net.revin.affine_weight)
        emit_array(f, "SAM_RV_B", net.revin.affine_bias)
        emit_array(f, "SAM_WQ", net.compute_queries.weight)    # (hid, L)
        emit_array(f, "SAM_BQ", net.compute_queries.bias)
        emit_array(f, "SAM_WK", net.compute_keys.weight)       # (hid, L)
        emit_array(f, "SAM_BK", net.compute_keys.bias)
        emit_array(f, "SAM_WV", net.compute_values.weight)     # (L, L)
        emit_array(f, "SAM_BV", net.compute_values.bias)
        emit_array(f, "SAM_WF", net.linear_forecaster.weight)  # (H, L)
        emit_array(f, "SAM_BF", net.linear_forecaster.bias)
        f.write("#endif /* SAMFORMER_WEIGHTS_H */\n")

    with (OUT_DIR / "samformer_vectors.h").open("w", newline="\n") as f:
        f.write("/* Auto-generated by deployment/board/export_golden_samformer.py - do not edit. */\n")
        f.write(f"/* weight_seed={WEIGHT_SEED}, input_seed={INPUT_SEED} */\n")
        f.write("#ifndef SAMFORMER_VECTORS_H\n#define SAMFORMER_VECTORS_H\n\n")
        emit_array(f, "SFG_X", x[0])              # (L, D)
        emit_array(f, "SFG_MEAN", mean)
        emit_array(f, "SFG_STD", std)
        emit_array(f, "SFG_ATTW", attw)           # (D, D)
        emit_array(f, "SFG_OUT", cap["out"][0])   # (D, L)
        emit_array(f, "SFG_Y", y_ref[0])          # (H, D)
        f.write("#endif /* SAMFORMER_VECTORS_H */\n")

    print(f"wrote {OUT_DIR / 'samformer_weights.h'}")
    print(f"wrote {OUT_DIR / 'samformer_vectors.h'}")


if __name__ == "__main__":
    main()
